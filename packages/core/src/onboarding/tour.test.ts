import { describe, expect, it } from 'vitest'
import { createOnboardingTour } from './tour'

function reachSave() {
  const tour = createOnboardingTour()
  tour.start(); tour.next(); tour.event({ type: 'library-opened' }); tour.event({ type: 'deck-form-opened' })
  tour.setReady('deck-name', true); tour.next()
  return tour
}
describe('interactive onboarding', () => {
  it('requires entered fields and successful actions, rather than next-button shortcuts', () => {
    const tour = createOnboardingTour()
    tour.start(); tour.next(); tour.event({ type: 'library-opened' }); tour.next()
    expect(tour.getSnapshot()?.step).toBe('new-deck')
    tour.event({ type: 'deck-form-opened' }); tour.next()
    expect(tour.getSnapshot()?.step).toBe('deck-name')
    tour.setReady('answer', true); tour.next()
    expect(tour.getSnapshot()?.step).toBe('deck-name')
    tour.setReady('deck-name', true); tour.next(); tour.next()
    expect(tour.getSnapshot()?.step).toBe('deck-save')
  })
  it('follows only the deck and card made in this tour', () => {
    const tour = reachSave()
    tour.event({ type: 'deck-created', deckId: 'mine' })
    expect(tour.getSnapshot()?.step).toBe('open-deck')
    tour.next(); tour.event({ type: 'deck-opened', deckId: 'wrong' })
    expect(tour.getSnapshot()?.step).toBe('open-deck')
    tour.event({ type: 'deck-opened', deckId: 'mine' })
    tour.event({ type: 'card-chooser-opened', deckId: 'other' })
    expect(tour.getSnapshot()?.step).toBe('add-card')
    tour.event({ type: 'card-chooser-opened', deckId: 'mine' }); tour.event({ type: 'card-type-selected' })
    tour.setReady('prompt', true); tour.next(); tour.setReady('answer', true); tour.next()
    tour.event({ type: 'card-created', deckId: 'other', cardId: 'wrong' })
    expect(tour.getSnapshot()?.step).toBe('card-save')
    tour.event({ type: 'card-created', deckId: 'mine', cardId: 'card' })
    tour.event({ type: 'review-opened', deckId: 'other' })
    expect(tour.getSnapshot()?.step).toBe('study')
    tour.event({ type: 'review-opened', deckId: 'mine' })
    tour.event({ type: 'answer-revealed', cardId: 'wrong' })
    expect(tour.getSnapshot()?.step).toBe('reveal')
    tour.event({ type: 'answer-revealed', cardId: 'card' }); tour.next()
    expect(tour.getSnapshot()?.step).toBe('rate')
    tour.event({ type: 'review-saved', cardId: 'wrong' })
    expect(tour.getSnapshot()?.step).toBe('rate')
    tour.event({ type: 'review-saved', cardId: 'card' }); tour.next()
    expect(tour.getSnapshot()?.step).toBe('finish-review')
    tour.event({ type: 'session-exited' }); tour.event({ type: 'navigation-ready' }); tour.next()
    expect(tour.getSnapshot()?.step).toBe('open-progress')
    tour.event({ type: 'progress-opened' }); tour.next()
    expect(tour.getSnapshot()?.step).toBe('complete')
  })
  it('stops immediately and replays from a fresh scenario', () => {
    const tour = reachSave()
    tour.stop(); tour.event({ type: 'deck-created', deckId: 'late' })
    expect(tour.getSnapshot()).toBeNull()
    tour.start()
    expect(tour.getSnapshot()).toEqual({ step: 'today', ready: false })
  })
})
